using System;
using System.Reflection;
using System.Reflection.Emit;
using System.Runtime.CompilerServices;
using System.Runtime.Loader;
using System.Threading;
using System.Threading.Tasks;
using Microsoft.Azure.WebJobs.Host.Listeners;
using Microsoft.Extensions.Logging;

namespace Azure.Functions.Rpc.Client;

/// <summary>
/// Pauses the shared Event Grid Blob queue pump without stopping its one-shot SDK timer.
/// </summary>
internal partial class BlobListenerQueueGate : DispatchProxy
{
    private const string BlobsNamespace = "Microsoft.Azure.WebJobs.Extensions.Storage.Blobs.Listeners.";
    private const string CommonNamespace = "Microsoft.Azure.WebJobs.Extensions.Storage.Common.";
    private static readonly ConditionalWeakTable<AssemblyLoadContext, Type> ProxyBaseTypes = new();
    private readonly Lock _lock = new();
    private TaskCompletionSource _resumed = new(TaskCreationOptions.RunContinuationsAsynchronously);
    private Func<CancellationToken, object> _execute;
    private ILogger _logger;
    private bool _enabled;

    /// <summary>
    /// Initializes a new instance of the <see cref="BlobListenerQueueGate"/> class.
    /// Initializes a proxy generated by <see cref="DispatchProxy"/>.
    /// </summary>
    public BlobListenerQueueGate()
    {
    }

    /// <summary>
    /// Installs one initially closed gate per shared SDK timer, before any function starts its listener.
    /// </summary>
    internal static BlobListenerQueueGate Install(IListener listener, ILogger logger)
    {
        ArgumentNullException.ThrowIfNull(listener);
        ArgumentNullException.ThrowIfNull(logger);
        Assembly assembly = listener.GetType().Assembly;
        try
        {
            Type blobListenerType = assembly.GetType(BlobsNamespace + "BlobListener", throwOnError: true);
            Type sharedListenerType = assembly.GetType(BlobsNamespace + "SharedBlobQueueListener", throwOnError: true);
            Type queueListenerType = assembly.GetType(CommonNamespace + "Listeners.QueueListener", throwOnError: true);
            Type timerType = assembly.GetType(CommonNamespace + "Timers.TaskSeriesTimer", throwOnError: true);
            Type commandType = assembly.GetType(CommonNamespace + "Timers.ITaskSeriesCommand", throwOnError: true);
            Type resultType = assembly.GetType(CommonNamespace + "Timers.TaskSeriesCommandResult", throwOnError: true);
            object shared = ReadField(listener, blobListenerType, "_sharedListener",
                assembly.GetType(CommonNamespace + "Listeners.ISharedListener", throwOnError: true));
            object queue = ReadField(shared, sharedListenerType, "_listener", typeof(IListener));
            object timer = ReadField(queue, queueListenerType, "_timer",
                assembly.GetType(CommonNamespace + "Timers.ITaskSeriesTimer", throwOnError: true));
            FieldInfo commandField = GetField(timerType, "_command", commandType);
            if (timer.GetType() != timerType)
            {
                throw new InvalidOperationException("The shared Blob queue timer has an unexpected type.");
            }

            object command = commandField.GetValue(timer);
            if (command is BlobListenerQueueGate existing)
            {
                return existing;
            }

            MethodInfo[] methods = commandType.GetMethods();
            if (!ReferenceEquals(command, queue) || !commandType.IsInterface || methods.Length != 1 ||
                !string.Equals(methods[0].Name, "ExecuteAsync", StringComparison.Ordinal) ||
                methods[0].ReturnType != typeof(Task<>).MakeGenericType(resultType) ||
                methods[0].GetParameters() is not [{ ParameterType: var parameterType }] || parameterType != typeof(CancellationToken))
            {
                throw new InvalidOperationException("The shared Blob queue command has an unexpected contract.");
            }

            BlobListenerQueueGate gate = CreateProxy(commandType);
            typeof(BlobListenerQueueGate).GetMethod(nameof(BindCommand), BindingFlags.Instance | BindingFlags.NonPublic)
                .MakeGenericMethod(resultType).Invoke(gate, [command, methods[0], logger]);
            commandField.SetValue(timer, gate);
            if (!ReferenceEquals(commandField.GetValue(timer), gate))
            {
                throw new InvalidOperationException("The shared Blob queue command could not be replaced.");
            }

            return gate;
        }
        catch (Exception exception)
        {
            throw new NotSupportedException(
                $"Azure Storage Blobs extension '{assembly.FullName}' is not supported for worker-gated Event Grid Blob listeners. " +
                "The shared queue listener could not be gated using this extension version.", exception);
        }
    }

    internal static BlobListenerQueueGate CreateProxy(Type commandType)
    {
        AssemblyLoadContext context = AssemblyLoadContext.GetLoadContext(commandType.Assembly)
            ?? throw new InvalidOperationException("The Blob queue command has no assembly load context.");
        Type proxyBaseType = context == AssemblyLoadContext.GetLoadContext(typeof(BlobListenerQueueGate).Assembly)
            ? typeof(BlobListenerQueueGate)
            : ProxyBaseTypes.GetValue(context, CreateProxyBaseType);

        using (context.EnterContextualReflection())
        {
            BlobListenerQueueGate gate = (BlobListenerQueueGate)Create(commandType, proxyBaseType);
            if (!commandType.IsInstanceOfType(gate))
            {
                throw new InvalidOperationException("The shared Blob queue proxy has an unexpected command type.");
            }

            return gate;
        }
    }

    // Called only by the manager's reconciliation loop, never by asynchronous per-function start/stop operations.
    internal void SetEnabled(bool enabled)
    {
        lock (_lock)
        {
            if (_enabled == enabled)
            {
                return;
            }

            _enabled = enabled;
            if (enabled)
            {
                Log.BlobQueueResumed(_logger);
                _resumed.TrySetResult();
            }
            else
            {
                _resumed = new(TaskCreationOptions.RunContinuationsAsynchronously);
                Log.BlobQueuePaused(_logger);
            }
        }
    }

    internal void Initialize<TResult>(Func<CancellationToken, Task<TResult>> command, ILogger logger)
    {
        _logger = logger;
        _execute = token => ExecuteAsync(command, token);
    }

    /// <inheritdoc />
    protected override object Invoke(MethodInfo targetMethod, object[] args) => _execute((CancellationToken)args[0]);

    private void BindCommand<TResult>(object command, MethodInfo method, ILogger logger)
        => Initialize(method.CreateDelegate<Func<CancellationToken, Task<TResult>>>(command), logger);

    private async Task<TResult> ExecuteAsync<TResult>(Func<CancellationToken, Task<TResult>> command, CancellationToken cancellationToken)
    {
        while (true)
        {
            Task resumed;
            lock (_lock)
            {
                if (_enabled)
                {
                    break;
                }

                resumed = _resumed.Task;
            }

            // A close after a wake must be observed before admitting another queue receive.
            await resumed.WaitAsync(cancellationToken).ConfigureAwait(false);
        }

        cancellationToken.ThrowIfCancellationRequested();
        // Already-admitted receives and invocations may finish after a pause; the SDK retains their drain ownership.
        return await command(cancellationToken).ConfigureAwait(false);
    }

    private static object ReadField(object owner, Type ownerType, string name, Type fieldType)
    {
        if (owner.GetType() != ownerType)
        {
            throw new InvalidOperationException($"Expected listener type '{ownerType.FullName}', found '{owner.GetType().FullName}'.");
        }

        return GetField(ownerType, name, fieldType).GetValue(owner)
            ?? throw new InvalidOperationException($"Field '{ownerType.FullName}.{name}' is null.");
    }

    private static FieldInfo GetField(Type ownerType, string name, Type fieldType)
    {
        FieldInfo field = ownerType.GetField(name, BindingFlags.Instance | BindingFlags.NonPublic)
            ?? throw new MissingFieldException(ownerType.FullName, name);
        if (field.FieldType != fieldType || !field.IsInitOnly)
        {
            throw new InvalidOperationException($"Field '{ownerType.FullName}.{name}' has an unexpected contract.");
        }

        return field;
    }

    // DispatchProxy groups generated types by the base type's load context. A base type in each extension
    // context prevents overlapping ScriptHosts from binding identical extension identities to the wrong host.
    private static Type CreateProxyBaseType(AssemblyLoadContext context)
    {
        using (context.EnterContextualReflection())
        {
            AssemblyBuilder assembly = AssemblyBuilder.DefineDynamicAssembly(
                new AssemblyName("BlobListenerQueueGateProxyBase"),
                context.IsCollectible ? AssemblyBuilderAccess.RunAndCollect : AssemblyBuilderAccess.Run);
            ModuleBuilder module = assembly.DefineDynamicModule("BlobListenerQueueGateProxyBase");
            TypeBuilder attribute = module.DefineType("System.Runtime.CompilerServices.IgnoresAccessChecksToAttribute",
                TypeAttributes.NotPublic | TypeAttributes.Sealed | TypeAttributes.Class, typeof(Attribute));
            ConstructorBuilder constructor = attribute.DefineConstructor(MethodAttributes.Public, CallingConventions.Standard, [typeof(string)]);
            ILGenerator il = constructor.GetILGenerator();
            il.Emit(OpCodes.Ldarg_0);
            il.Emit(OpCodes.Call, typeof(Attribute).GetConstructor(BindingFlags.Instance | BindingFlags.NonPublic, null, Type.EmptyTypes, null));
            il.Emit(OpCodes.Ret);
            Type attributeType = attribute.CreateType();
            assembly.SetCustomAttribute(new CustomAttributeBuilder(attributeType.GetConstructor([typeof(string)]),
                [typeof(BlobListenerQueueGate).Assembly.GetName().Name]));

            TypeBuilder proxyBase = module.DefineType("BlobListenerQueueGateProxyBase",
                TypeAttributes.Public | TypeAttributes.Class, typeof(BlobListenerQueueGate));
            proxyBase.DefineDefaultConstructor(MethodAttributes.Public);
            return proxyBase.CreateType();
        }
    }

    private static partial class Log
    {
        [LoggerMessage(0, LogLevel.Information, "Resuming the shared Event Grid Blob queue listener because a Blob worker is available.")]
        public static partial void BlobQueueResumed(ILogger logger);

        [LoggerMessage(1, LogLevel.Information, "Pausing the shared Event Grid Blob queue listener because no Blob worker is available.")]
        public static partial void BlobQueuePaused(ILogger logger);
    }
}
